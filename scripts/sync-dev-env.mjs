#!/usr/bin/env node
/**
 * Writes/updates .env.local with the current LAN IP so Expo Go on a physical device
 * can reach Metro (avoids exp://127.0.0.1 which only works on the same machine).
 *
 * Preserves any existing non-managed keys (Firebase, RevenueCat, etc.) so a restart
 * does not wipe local secrets required for web/native boot.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const port = process.env.EXPO_DEV_SERVER_PORT ?? '8081';

const ipResult = spawnSync('node', ['scripts/get-lan-ip.mjs'], {
  cwd: process.cwd(),
  encoding: 'utf8',
  shell: true,
});

const lanIp = ipResult.stdout?.trim();
if (!lanIp) {
  console.warn('[sync-dev-env] Could not detect LAN IP — Expo Go on a phone may not connect.');
  process.exit(0);
}

const MANAGED_KEYS = new Set([
  'REACT_NATIVE_PACKAGER_HOSTNAME',
  'EXPO_DEV_SERVER_PORT',
  'EXPO_PUBLIC_APP_CHECK_ENABLED',
  'EXPO_PUBLIC_EXPO_GO',
]);

const target = resolve(process.cwd(), '.env.local');
const preserved = new Map();

if (existsSync(target)) {
  for (const rawLine of readFileSync(target, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trimEnd();
    if (!line || line.trimStart().startsWith('#')) {
      continue;
    }
    const eq = line.indexOf('=');
    if (eq <= 0) {
      continue;
    }
    const key = line.slice(0, eq).trim();
    if (!MANAGED_KEYS.has(key)) {
      preserved.set(key, line.slice(eq + 1));
    }
  }
}

const managed = [
  `REACT_NATIVE_PACKAGER_HOSTNAME=${lanIp}`,
  `EXPO_DEV_SERVER_PORT=${port}`,
  'EXPO_PUBLIC_APP_CHECK_ENABLED=false',
  'EXPO_PUBLIC_EXPO_GO=1',
];

const preservedLines = [...preserved.entries()].map(([key, value]) => `${key}=${value}`);

const content = [
  '# Auto-generated by scripts/sync-dev-env.mjs — managed keys below are refreshed on each start.',
  '# Other keys already present in this file are preserved.',
  '# Re-run "npm start" to refresh the LAN IP after changing Wi-Fi networks.',
  ...managed,
  ...(preservedLines.length
    ? ['', '# Preserved local configuration', ...preservedLines]
    : [
        '',
        '# No preserved Firebase/API keys found. Copy from .env.example or your secret store:',
        '# EXPO_PUBLIC_FIREBASE_API_KEY=...',
        '# EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN=...',
        '# EXPO_PUBLIC_FIREBASE_PROJECT_ID=...',
        '# EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET=...',
        '# EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=...',
        '# EXPO_PUBLIC_FIREBASE_APP_ID=...',
      ]),
  '',
].join('\n');

writeFileSync(target, content, 'utf8');

console.log(`[sync-dev-env] LAN IP ${lanIp} → exp://${lanIp}:${port}`);
console.log(`[sync-dev-env] Wrote ${target} (preserved ${preserved.size} key(s))`);
