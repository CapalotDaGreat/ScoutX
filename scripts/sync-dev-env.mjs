#!/usr/bin/env node
/**
 * Writes .env.local with the current LAN IP so Expo Go on a physical device
 * can reach Metro (avoids exp://127.0.0.1 which only works on the same machine).
 */
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const port = process.env.EXPO_DEV_SERVER_PORT ?? '8081';

const ipResult = spawnSync('node', ['scripts/get-lan-ip.mjs'], {
  cwd: process.cwd(),
  encoding: 'utf8',
  shell: true,
});

const lanIp = ipResult.stdout?.trim();
if (!lanIp) {
  console.warn('[sync-dev-env] Could not detect LAN IP — Expo Go on a phone may not connect.');
  process.exit(0);
}

const content = `# Auto-generated by scripts/sync-dev-env.mjs — do not edit manually.
# Re-run "npm start" to refresh after changing Wi-Fi networks.
REACT_NATIVE_PACKAGER_HOSTNAME=${lanIp}
EXPO_DEV_SERVER_PORT=${port}
EXPO_PUBLIC_APP_CHECK_ENABLED=false
EXPO_PUBLIC_EXPO_GO=1
`;

const target = resolve(process.cwd(), '.env.local');
writeFileSync(target, content, 'utf8');

console.log(`[sync-dev-env] LAN IP ${lanIp} → exp://${lanIp}:${port}`);
console.log(`[sync-dev-env] Wrote ${target}`);
