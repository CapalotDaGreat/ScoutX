#!/usr/bin/env node
/**
 * Compiles legal/documents/*.md into src/features/legal/content.generated.ts.
 *
 *   node scripts/build-legal.mjs          # write the generated module
 *   node scripts/build-legal.mjs --check  # exit 1 if the generated module is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = new URL('../', import.meta.url);
const OUTPUT = new URL('src/features/legal/content.generated.ts', ROOT);
const SERVER_OUTPUT = new URL('functions/src/legal/legalVersions.generated.ts', ROOT);

/** Display order in the Privacy Center. */
export const LEGAL_DOCUMENT_ORDER = [
  'privacy-policy',
  'terms-of-service',
  'community-guidelines',
  'youth-safety-policy',
  'guardian-consent-notice',
  'video-recording-policy',
  'ai-use-policy',
  'copyright-policy',
  'reporting-takedown-policy',
  'data-subject-rights',
  'data-retention-policy',
  'security-disclosure-policy',
  'cookie-tracking-policy',
  'subscription-terms',
];

const REQUIRED_KEYS = ['id', 'title', 'version', 'effectiveDate', 'status', 'canonicalLanguage', 'requiresAcceptance'];

function parseFrontMatter(raw, file) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/.exec(raw);
  if (!match) throw new Error(`${file}: missing front matter`);
  const meta = { summary: [] };
  let inSummary = false;
  for (const line of match[1].split(/\r?\n/)) {
    if (inSummary && line.startsWith('- ')) {
      meta.summary.push(line.slice(2).trim());
      continue;
    }
    inSummary = false;
    const pair = /^(\w+):\s*(.*)$/.exec(line);
    if (!pair) throw new Error(`${file}: unparseable front matter line "${line}"`);
    if (pair[1] === 'summary') {
      inSummary = true;
      continue;
    }
    meta[pair[1]] = pair[2].trim();
  }
  for (const key of REQUIRED_KEYS) {
    if (!meta[key]) throw new Error(`${file}: front matter is missing "${key}"`);
  }
  if (!/^\d+\.\d+\.\d+$/.test(meta.version)) throw new Error(`${file}: version must be semver`);
  if (meta.summary.length === 0) throw new Error(`${file}: summary is empty`);
  return { meta, body: match[2] };
}

function parseBlocks(text) {
  return text
    .split(/\r?\n\s*\r?\n/)
    .map((chunk) => chunk.split(/\r?\n/).map((line) => line.trim()).filter(Boolean))
    .filter((lines) => lines.length > 0)
    .map((lines) => {
      if (lines.every((line) => line.startsWith('- '))) {
        return { type: 'list', ordered: false, items: lines.map((line) => line.slice(2)) };
      }
      if (lines.every((line) => /^\d+\.\s/.test(line))) {
        return { type: 'list', ordered: true, items: lines.map((line) => line.replace(/^\d+\.\s/, '')) };
      }
      return { type: 'paragraph', text: lines.join(' ') };
    });
}

function parseSections(body, file) {
  const parts = body.split(/^## /m);
  if (parts[0].trim()) throw new Error(`${file}: text before the first "## " heading`);
  return parts.slice(1).map((part) => {
    const newline = part.indexOf('\n');
    const heading = (newline === -1 ? part : part.slice(0, newline)).trim();
    return { heading, blocks: parseBlocks(newline === -1 ? '' : part.slice(newline + 1)) };
  });
}

export function loadLegalDocuments(root = ROOT) {
  return LEGAL_DOCUMENT_ORDER.map((id) => {
    const file = `legal/documents/${id}.md`;
    const { meta, body } = parseFrontMatter(readFileSync(new URL(file, root), 'utf8'), file);
    if (meta.id !== id) throw new Error(`${file}: id "${meta.id}" does not match file name`);
    return {
      id,
      title: meta.title,
      version: meta.version,
      effectiveDate: meta.effectiveDate,
      status: meta.status,
      canonicalLanguage: meta.canonicalLanguage,
      requiresAcceptance: meta.requiresAcceptance === 'true',
      summary: meta.summary,
      sections: parseSections(body, file),
    };
  });
}

export function renderLegalModule(root = ROOT) {
  const documents = loadLegalDocuments(root);
  return [
    '// Generated by scripts/build-legal.mjs from legal/documents/*.md. Do not edit by hand.',
    "import type { LegalDocument } from '@/features/legal/types';",
    '',
    `export const LEGAL_DOCUMENTS: readonly LegalDocument[] = ${JSON.stringify(documents, null, 2)};`,
    '',
  ].join('\n');
}

/** The server records consent against these versions, never against a client-supplied one. */
export function renderServerVersions(root = ROOT) {
  const versions = Object.fromEntries(loadLegalDocuments(root).map((doc) => [doc.id, doc.version]));
  return [
    '// Generated by scripts/build-legal.mjs from legal/documents/*.md. Do not edit by hand.',
    '',
    `export const LEGAL_VERSIONS: Readonly<Record<string, string>> = ${JSON.stringify(versions, null, 2)};`,
    '',
  ].join('\n');
}

const OUTPUTS = [
  { url: OUTPUT, label: 'src/features/legal/content.generated.ts', render: renderLegalModule },
  { url: SERVER_OUTPUT, label: 'functions/src/legal/legalVersions.generated.ts', render: renderServerVersions },
];

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const output of OUTPUTS) {
    const next = output.render();
    if (check) {
      let current = '';
      try {
        current = readFileSync(output.url, 'utf8');
      } catch {
        // Missing file is stale.
      }
      if (current.replace(/\r\n/g, '\n') !== next) {
        console.error(`${output.label} is out of date. Run: node scripts/build-legal.mjs`);
        stale = true;
      }
    } else {
      writeFileSync(output.url, next);
      console.log(`Wrote ${output.label}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log('Legal content is up to date.');
}
