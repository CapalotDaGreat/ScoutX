export async function renderSite(root = ROOT) {
  const legal = await import(new URL('src/config/legalConfig.ts', root).href);
  const resolve = (text) => legal.resolveLegalTokens(text);
  const documents = loadLegalDocuments(root);
  for (const doc of documents) {
    const groups = POLICY_GROUPS.filter((group) => group.documents.includes(doc.id));
    if (groups.length !== 1) throw new Error(`${doc.id}: must belong to exactly one policy group on the website`);
  }
  const site = { entityName: legal.LEGAL_CONFIG.entity.name, entityAddress: legal.entityAddress() };
  const files = [
    { label: 'public/support/index.html', content: renderSupportPage(legal, site) },
    { label: 'public/legal/index.html', content: renderLegalIndex(documents, resolve, site) },
  ];
  for (const doc of documents) {
    const page = renderDocumentPage(doc, documents, resolve, site);
    files.push({ label: `public/legal/${doc.id}/index.html`, content: page });
    if (SITE_PAGES[doc.id]) files.push({ label: `public/${SITE_PAGES[doc.id]}/index.html`, content: page });
  }
  return files;
}

const OUTPUTS = [
  { url: OUTPUT, label: 'src/features/legal/content.generated.ts', render: renderLegalModule },
  { url: SERVER_OUTPUT, label: 'functions/src/legal/legalVersions.generated.ts', render: renderServerVersions },
  ...(await renderSite()).map((file) => ({ url: new URL(file.label, ROOT), label: file.label, render: () => file.content })),
];

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const output of OUTPUTS) {
    const next = output.render();
    if (check) {
      let current = '';
      try {
        current = readFileSync(output.url, 'utf8');
      } catch {
        // Missing file is stale.
      }
      if (current.replace(/\r\n/g, '\n') !== next) {
        console.error(`${output.label} is out of date. Run: node scripts/build-legal.mjs`);
        stale = true;
      }
    } else {
      mkdirSync(new URL('.', output.url), { recursive: true });
      writeFileSync(output.url, next);
      console.log(`Wrote ${output.label}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log('Legal content is up to date.');
}
