function renderBlocks(blocks, resolve, found) {
  return blocks
    .map((block) => {
      if (block.type === 'paragraph') return `<p>${richText(resolve(block.text), found)}</p>`;
      const tag = block.ordered ? 'ol' : 'ul';
      return `<${tag}>${block.items.map((item) => `<li>${richText(resolve(item), found)}</li>`).join('')}</${tag}>`;
    })
    .join('\n');
}

function groupFor(id) {
  return POLICY_GROUPS.find((group) => group.documents.includes(id));
}

function readingMinutes(doc) {
  const words = doc.sections
    .flatMap((section) => [section.heading, ...section.blocks.flatMap((block) => (block.type === 'paragraph' ? [block.text] : block.items))])
    .join(' ')
    .split(/\s+/).length;
  return Math.max(1, Math.round(words / 220));
}

function draftNotice(doc) {
  if (!isDraft(doc)) return '';
  return `<div class="notice" role="note">${icon('document')}<div><strong>Draft under legal review.</strong> This version is published for transparency. The effective date will be set once the review is complete.</div></div>`;
}

function renderDocumentPage(doc, documents, resolve, site) {
  const found = new Set();
  if (!isIsoDate(doc.effectiveDate)) found.add(doc.effectiveDate);
  const group = groupFor(doc.id);
  const sections = doc.sections.map((section, index) => ({
    ...section,
    number: index + 1,
    anchor: slugify(resolve(section.heading)) || `section-${index + 1}`,
  }));
  const toc = sections
    .map((section) => `<li><a href="#${section.anchor}"><span class="n">${section.number}</span><span>${escapeHtml(resolve(section.heading))}</span></a></li>`)
    .join('');
  const body = sections
    .map(
      (section) => `<section class="doc-section" id="${section.anchor}">
<h2><span class="n">${section.number}</span><a href="#${section.anchor}">${escapeHtml(resolve(section.heading))}</a></h2>
${renderBlocks(section.blocks, resolve, found)}
</section>`,
    )
    .join('\n');
  const summary = doc.summary.map((item) => `<li>${richText(resolve(item), found)}</li>`).join('');
  const related = group.documents
    .filter((id) => id !== doc.id)
    .map((id) => documents.find((candidate) => candidate.id === id))
    .map(
      (other) => `<a class="card" href="/legal/${other.id}/"><h3>${escapeHtml(other.title)}</h3><p>${richText(resolve(other.summary[0]), found)}</p><span class="foot"><span class="go">Read ${icon('arrow')}</span></span></a>`,
    )
    .join('');
  const effective = isIsoDate(doc.effectiveDate)
    ? `<li>Effective ${escapeHtml(formatDate(doc.effectiveDate))}</li>`
    : '<li class="warn">Effective date pending legal review</li>';

  return pageShell(
    {
      title: doc.title,
      description: resolve(doc.summary[0]).replace(PLACEHOLDER, '').trim(),
      path: SITE_PAGES[doc.id] ? `/${SITE_PAGES[doc.id]}/` : `/legal/${doc.id}/`,
      current: 'legal',
      placeholders: found,
      script: TOC_SCRIPT,
      body: `<section class="hero">
  <div class="wrap">
    <nav class="crumbs" aria-label="Breadcrumb"><a href="/legal/">Policies</a><span aria-hidden="true">/</span><a href="/legal/#${slugify(group.title)}">${escapeHtml(group.title)}</a></nav>
    <p class="eyebrow">${icon(group.icon)}${escapeHtml(group.short)}</p>
    <h1>${escapeHtml(doc.title)}</h1>
    <ul class="pills">
      <li>Version ${escapeHtml(doc.version)}</li>
      ${effective}
      <li>${readingMinutes(doc)} min read</li>
      <li>Original language: ${doc.canonicalLanguage === 'en' ? 'English' : escapeHtml(doc.canonicalLanguage)}</li>
    </ul>
    ${draftNotice(doc)}
  </div>
</section>
<div class="wrap layout">
  <aside class="toc" aria-label="On this page">
    <details open>
      <summary>On this page</summary>
      <ol>${toc}</ol>
    </details>
    <p class="print"><button type="button">Print or save as PDF</button></p>
  </aside>
  <article>
    <div class="summary">
      <p class="kicker">In short</p>
      <ul class="points">${summary}</ul>
    </div>
    <div class="sections">
${body}
    </div>
    <div class="help">
      <div>
        <h2>Questions about this policy?</h2>
        <p>Our support page explains how to reach us. The same text is available in the app under Settings → Privacy Center.</p>
      </div>
      <a class="btn ghost" href="/support/">Contact support</a>
    </div>
    <section class="related" aria-labelledby="related-title">
      <p class="kicker" id="related-title">More in ${escapeHtml(group.title)}</p>
      <div class="grid">${related}</div>
    </section>
  </article>
</div>`,
    },
    site,
  );
}

function contactLine(value, found) {
  const text = richText(value, found);
  return /@/.test(value) && !hasPlaceholder(value) ? `<a href="mailto:${escapeHtml(value)}">${text}</a>` : text;
}

