function escapeHtml(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

const PLACEHOLDER = /\b(?:LEGAL|PRIVACY|SECURITY)_CONTACT_REQUIRED\b|\bLEGAL_REVIEW_REQUIRED\b/g;
const hasPlaceholder = (text) => new RegExp(PLACEHOLDER.source).test(text);

/** Escapes text and shows unfilled config placeholders as readable badges, recording each one. */
function richText(text, found) {
  return escapeHtml(text).replace(PLACEHOLDER, (token) => {
    found.add(token);
    const label = token === 'LEGAL_REVIEW_REQUIRED' ? 'pending legal review' : 'to be published';
    return `<span class="pending" title="${token}">${label}</span>`;
  });
}

function slugify(text) {
  return text
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const isIsoDate = (value) => /^\d{4}-\d{2}-\d{2}$/.test(value);

function formatDate(value) {
  return new Date(`${value}T00:00:00Z`).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
}

function isDraft(doc) {
  return !isIsoDate(doc.effectiveDate) || /draft|review/i.test(doc.status);
}

