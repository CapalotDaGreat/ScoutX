#!/usr/bin/env node
/**
 * Compiles legal/documents/*.md into src/features/legal/content.generated.ts, the server version
 * table, and the public website pages under public/ (privacy, terms, subscription terms, support).
 *
 *   node scripts/build-legal.mjs          # write the generated module
 *   node scripts/build-legal.mjs --check  # exit 1 if the generated module is stale
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = new URL('../', import.meta.url);
const OUTPUT = new URL('src/features/legal/content.generated.ts', ROOT);
const SERVER_OUTPUT = new URL('functions/src/legal/legalVersions.generated.ts', ROOT);

/** Display order in the Privacy Center. */
export const LEGAL_DOCUMENT_ORDER = [
  'privacy-policy',
  'terms-of-service',
  'community-guidelines',
  'youth-safety-policy',
  'guardian-consent-notice',
  'video-recording-policy',
  'ai-use-policy',
  'copyright-policy',
  'reporting-takedown-policy',
  'data-subject-rights',
  'data-retention-policy',
  'security-disclosure-policy',
  'cookie-tracking-policy',
  'subscription-terms',
];

const REQUIRED_KEYS = ['id', 'title', 'version', 'effectiveDate', 'status', 'canonicalLanguage', 'requiresAcceptance'];

function parseFrontMatter(raw, file) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/.exec(raw);
  if (!match) throw new Error(`${file}: missing front matter`);
  const meta = { summary: [] };
  let inSummary = false;
  for (const line of match[1].split(/\r?\n/)) {
    if (inSummary && line.startsWith('- ')) {
      meta.summary.push(line.slice(2).trim());
      continue;
    }
    inSummary = false;
    const pair = /^(\w+):\s*(.*)$/.exec(line);
    if (!pair) throw new Error(`${file}: unparseable front matter line "${line}"`);
    if (pair[1] === 'summary') {
      inSummary = true;
      continue;
    }
    meta[pair[1]] = pair[2].trim();
  }
  for (const key of REQUIRED_KEYS) {
    if (!meta[key]) throw new Error(`${file}: front matter is missing "${key}"`);
  }
  if (!/^\d+\.\d+\.\d+$/.test(meta.version)) throw new Error(`${file}: version must be semver`);
  if (meta.summary.length === 0) throw new Error(`${file}: summary is empty`);
  return { meta, body: match[2] };
}

function parseBlocks(text) {
  return text
    .split(/\r?\n\s*\r?\n/)
    .map((chunk) => chunk.split(/\r?\n/).map((line) => line.trim()).filter(Boolean))
    .filter((lines) => lines.length > 0)
    .map((lines) => {
      if (lines.every((line) => line.startsWith('- '))) {
        return { type: 'list', ordered: false, items: lines.map((line) => line.slice(2)) };
      }
      if (lines.every((line) => /^\d+\.\s/.test(line))) {
        return { type: 'list', ordered: true, items: lines.map((line) => line.replace(/^\d+\.\s/, '')) };
      }
      return { type: 'paragraph', text: lines.join(' ') };
    });
}

function parseSections(body, file) {
  const parts = body.split(/^## /m);
  if (parts[0].trim()) throw new Error(`${file}: text before the first "## " heading`);
  return parts.slice(1).map((part) => {
    const newline = part.indexOf('\n');
    const heading = (newline === -1 ? part : part.slice(0, newline)).trim();
    return { heading, blocks: parseBlocks(newline === -1 ? '' : part.slice(newline + 1)) };
  });
}

export function loadLegalDocuments(root = ROOT) {
  return LEGAL_DOCUMENT_ORDER.map((id) => {
    const file = `legal/documents/${id}.md`;
    const { meta, body } = parseFrontMatter(readFileSync(new URL(file, root), 'utf8'), file);
    if (meta.id !== id) throw new Error(`${file}: id "${meta.id}" does not match file name`);
    return {
      id,
      title: meta.title,
      version: meta.version,
      effectiveDate: meta.effectiveDate,
      status: meta.status,
      canonicalLanguage: meta.canonicalLanguage,
      requiresAcceptance: meta.requiresAcceptance === 'true',
      summary: meta.summary,
      sections: parseSections(body, file),
    };
  });
}

export function renderLegalModule(root = ROOT) {
  const documents = loadLegalDocuments(root);
  return [
    '// Generated by scripts/build-legal.mjs from legal/documents/*.md. Do not edit by hand.',
    "import type { LegalDocument } from '@/features/legal/types';",
    '',
    `export const LEGAL_DOCUMENTS: readonly LegalDocument[] = ${JSON.stringify(documents, null, 2)};`,
    '',
  ].join('\n');
}

/** The server records consent against these versions, never against a client-supplied one. */
export function renderServerVersions(root = ROOT) {
  const versions = Object.fromEntries(loadLegalDocuments(root).map((doc) => [doc.id, doc.version]));
  return [
    '// Generated by scripts/build-legal.mjs from legal/documents/*.md. Do not edit by hand.',
    '',
    `export const LEGAL_VERSIONS: Readonly<Record<string, string>> = ${JSON.stringify(versions, null, 2)};`,
    '',
  ].join('\n');
}

// Public website pages (Firebase Hosting, `public/`). The App Store privacy policy, terms and
// support URLs point here, so the web text is generated from the same source as the app.
// The landing page public/welcome/index.html is hand-written and not generated.
const SITE_NAME = 'PitchProof';
const SITE_PAGES = { 'privacy-policy': 'privacy', 'terms-of-service': 'terms', 'subscription-terms': 'subscription-terms' };

function escapeHtml(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function pageShell(title, body) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)} | ${SITE_NAME}</title>
<style>
:root { color-scheme: light dark; --bg: #F4EFE6; --card: #EBE3D4; --text: #1A1814; --muted: #5c564c; --accent: #1f8f53; }
@media (prefers-color-scheme: dark) { :root { --bg: #161412; --card: #1E1C19; --text: #F7F4EF; --muted: #b9b2a6; --accent: #2FBF71; } }
body { margin: 0; background: var(--bg); color: var(--text); font: 16px/1.6 -apple-system, BlinkMacSystemFont, "Inter", "Segoe UI", sans-serif; }
main { max-width: 760px; margin: 0 auto; padding: 32px 20px 64px; }
header a, footer a, main a { color: var(--accent); }
nav { display: flex; flex-wrap: wrap; gap: 16px; font-size: 14px; margin-bottom: 24px; }
h1 { font-size: 28px; line-height: 1.25; margin: 0 0 8px; }
h2 { font-size: 19px; margin: 32px 0 8px; }
.meta { color: var(--muted); font-size: 14px; }
.summary { background: var(--card); border-radius: 16px; padding: 16px 20px; margin: 20px 0; }
footer { color: var(--muted); font-size: 13px; margin-top: 48px; }
</style>
</head>
<body>
<main>
<nav><a href="/">${SITE_NAME}</a><a href="/privacy/">Privacy</a><a href="/terms/">Terms</a><a href="/subscription-terms/">Subscriptions</a><a href="/support/">Support</a><a href="/legal/">All policies</a></nav>
${body}
</main>
</body>
</html>
`;
}

function renderBlocks(blocks, resolve) {
  return blocks
    .map((block) => {
      if (block.type === 'paragraph') return `<p>${escapeHtml(resolve(block.text))}</p>`;
      const tag = block.ordered ? 'ol' : 'ul';
      return `<${tag}>${block.items.map((item) => `<li>${escapeHtml(resolve(item))}</li>`).join('')}</${tag}>`;
    })
    .join('\n');
}

function renderDocumentPage(doc, resolve) {
  const summary = doc.summary.map((item) => `<li>${escapeHtml(resolve(item))}</li>`).join('');
  const sections = doc.sections
    .map((section) => `<h2>${escapeHtml(resolve(section.heading))}</h2>\n${renderBlocks(section.blocks, resolve)}`)
    .join('\n');
  return pageShell(
    doc.title,
    `<h1>${escapeHtml(doc.title)}</h1>
<p class="meta">Version ${escapeHtml(doc.version)} · Effective ${escapeHtml(doc.effectiveDate)}</p>
<div class="summary"><strong>In short</strong><ul>${summary}</ul></div>
${sections}
<footer>The same text is available in the app under Settings → Privacy Center.</footer>`,
  );
}

