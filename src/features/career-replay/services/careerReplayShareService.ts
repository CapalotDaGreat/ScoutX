import * as Print from 'expo-print';
import { CareerReplayRepository } from '@/features/career-replay/repositories/CareerReplayRepository';
import { type CareerReplayData } from '@/features/career-replay/types';
import { shareFileUri } from '@/features/share-cards/services/shareCardService';
import { escapeHtml } from '@/utils/htmlEscape';

export async function shareCareerReplayPdf(data: CareerReplayData, playerId?: string): Promise<void> {
  const highlightRows = data.highlights
    .map(
      (item) =>
        `<div class="stat"><span>${escapeHtml(item.label)}</span><strong>${escapeHtml(item.value)}</strong></div>`,
    )
    .join('');

  const bestMatchLine =
    data.bestRating !== null && data.bestRatingOpponent
      ? `<p class="best">Best match rating: ${data.bestRating.toFixed(1)} vs ${escapeHtml(data.bestRatingOpponent)}</p>`
      : '';

  const html = `
    <html>
      <head>
        <meta charset="utf-8" />
        <style>
          body { font-family: Helvetica, Arial, sans-serif; color: #111; padding: 32px; background: #f8fafc; }
          .card { background: #fff; border-radius: 16px; padding: 28px; border: 1px solid #e2e8f0; }
          .badge { display: inline-block; background: #dcfce7; color: #166534; padding: 4px 10px; border-radius: 999px; font-size: 12px; }
          h1 { margin: 12px 0 4px; font-size: 28px; }
          .meta { color: #64748b; margin-bottom: 16px; }
          .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 12px; margin: 20px 0; }
          .stat { background: #f1f5f9; border-radius: 12px; padding: 12px; }
          .stat span { display: block; font-size: 11px; color: #64748b; text-transform: uppercase; }
          .stat strong { font-size: 22px; }
          .narrative { line-height: 1.5; color: #334155; }
          .best { margin-top: 12px; color: #166534; font-weight: 600; }
          .footer { margin-top: 24px; font-size: 11px; color: #94a3b8; }
        </style>
      </head>
      <body>
        <div class="card">
          <div class="badge">ScoutX Career Replay</div>
          <h1>${escapeHtml(data.playerName)}</h1>
          <div class="meta">${escapeHtml(data.seasonLabel)} · ${escapeHtml(data.position)} · ${escapeHtml(data.club)}</div>
          <div class="grid">${highlightRows}</div>
          <p class="narrative">${escapeHtml(data.narrative)}</p>
          ${bestMatchLine}
          <div class="footer">Generated by ScoutX Football Passport</div>
        </div>
      </body>
    </html>
  `;

  const file = await Print.printToFileAsync({ html });
  if (playerId) {
    await CareerReplayRepository.getInstance().saveReplay(playerId, data);
  }

  await shareFileUri(file.uri, {
    dialogTitle: `${data.playerName} — Career Replay`,
    mimeType: 'application/pdf',
  });
}

/** @deprecated Use shareCareerReplayPdf or useCareerReplayShare().shareAsImage */
export async function shareCareerReplayCard(data: CareerReplayData, playerId?: string): Promise<void> {
  await shareCareerReplayPdf(data, playerId);
}
